// Brews share one bottle; only the liquid colour changes.
const BOTTLE = ["..kkk...", "..klk...", "..klk...", ".kXXXk..", "kXwXXXk.", "kXXXXXk.", "kXXXXXk.", ".kkkkk.."];
const BREW_COLORS = { rushBrew: "y", fireBrew: "R", hotBrew: "r", luckBrew: "G", midasBrew: "Y", starBrew: "c", titanBrew: "S", breakerBrew: "B", phoenixBrew: "v", voidBrew: "p", hypeBrew: "P", surgeBrew: "O" };
Object.entries(BREW_COLORS).forEach(([id, c]) => (SPRITES[id] = BOTTLE.map((row) => row.replaceAll("X", c))));

const cache = new Map();

export function spriteCanvas(name) {
    if (cache.has(name)) return cache.get(name);
    const rows = SPRITES[name];
    const canvas = document.createElement("canvas");
    canvas.width = rows[0].length;
    canvas.height = rows.length;
    const ctx = canvas.getContext("2d");
    rows.forEach((row, y) => {
        [...row].forEach((ch, x) => {
            if (!PALETTE[ch]) return;
            ctx.fillStyle = PALETTE[ch];
            ctx.fillRect(x, y, 1, 1);
        });
    });
    cache.set(name, canvas);
    return canvas;
}

export function drawSprite(ctx, name, x, y, flip = false) {
    const img = spriteCanvas(name);
    if (!flip) return ctx.drawImage(img, Math.round(x), Math.round(y));
    ctx.save();
    ctx.scale(-1, 1);
    ctx.drawImage(img, -Math.round(x) - img.width, Math.round(y));
    ctx.restore();
}

// Every in-game icon is drawn this much bigger than the scale its caller asks for (callers think in the
// original 1x sizes). src/popup.css's pt type scale matches it.
export const UI_SCALE = 1.125;

export function svgIcon(name, scale = 2) {
    scale *= UI_SCALE;
    const rows = SPRITES[name] ?? SPRITES[`i-${name}`];
    const w = rows[0].length;
    const h = rows.length;
    let rects = "";
    rows.forEach((row, y) => {
        let x = 0;
        while (x < w) {
            const ch = row[x];
            let run = 1;
            while (x + run < w && row[x + run] === ch) run++;
            const fill = ch === "#" ? "currentColor" : PALETTE[ch];
            if (fill) rects += `<rect x="${x}" y="${y}" width="${run}" height="1" fill="${fill}"/>`;
            x += run;
        }
    });
    return `<svg class="ico" viewBox="0 0 ${w} ${h}" width="${w * scale}" height="${h * scale}" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
}

// A sprite in a fixed `box`-px square. Sprites come in many sizes (5x5 glyphs, 8x8 items, 10x12 pets, 12x14
// characters), so a shared scale makes them uneven. The square never changes size: the sprite takes the biggest
// whole-pixel scale that fills at least FIT_MIN of it (pixel-sharp), else an exact fit.
const FIT_MIN = 0.8;
export function svgFit(name, box) {
    box *= UI_SCALE;
    const rows = SPRITES[name] ?? SPRITES[`i-${name}`];
    const long = Math.max(rows[0].length, rows.length);
    const whole = Math.floor(box / long);
    const scale = whole >= 1 && whole * long >= box * FIT_MIN ? whole : box / long;
    return `<span class="ibox" style="--box:${box}px">${svgIcon(name, scale / UI_SCALE)}</span>`;
}

export function hydrateIcons(root = document) {
    root.querySelectorAll("[data-icon]").forEach((el) => {
        el.innerHTML = svgIcon(el.dataset.icon, Number(el.dataset.scale) || 2);
    });
}
